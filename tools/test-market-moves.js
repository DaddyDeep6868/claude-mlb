const fs=require('fs'), path=require('path'), vm=require('vm'), assert=require('assert');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const open='<script type="__bundler/template">', s=html.indexOf(open)+open.length, e=html.indexOf('</script>',s);
const tpl=JSON.parse(html.slice(s,e));
const m=tpl.match(/<script type="text\/x-dc"[^>]*>\n([\s\S]*?)<\/script>/);
assert(m,'component script found');
const mem={};
const sandbox={console,Date,JSON,Math,Set,Map,Promise,AbortController,localStorage:{getItem:k=>mem[k]||null,setItem:(k,v)=>{mem[k]=String(v)}},DCLogic:class{}};
vm.createContext(sandbox);
vm.runInContext(m[1]+'\n;globalThis.Component=Component;',sandbox,{filename:'Component.js'});
const app=Object.create(sandbox.Component.prototype);
const now=Date.now(), key=app.normName('Test Slugger');
function player(books,fair=21.5){return {id:1,name:'Test Slugger',teamAbbr:'TST',oddsPerBook:books,fairPct:fair};}
mem.dl_bookhist_v1=JSON.stringify({[key]:{snaps:[{t:now-10*60000,c:18.0,b:{draftkings:400,betmgm:410,caesars:420}}]}});
let r=app.marketMoves([player({draftkings:350,betmgm:360,caesars:420})],now);
assert.equal(r.steam.length,1,'two-book synchronized move triggers steam');
assert.equal(r.stale.length,1,'unmoved long book triggers stale');
assert.equal(r.stale[0].book,'Caesars');
assert.equal(r.shop[0].bestBook,'Caesars');
assert(r.steam[0].velocity>0,'velocity computed');
r=app.marketMoves([player({draftkings:350,betmgm:410,caesars:420})],now);
assert.equal(r.steam.length,0,'single-book repricing does not trigger steam');
mem.dl_bookhist_v1='{}';
r=app.marketMoves([player({draftkings:300,betmgm:450,caesars:320},22)],now);
assert.equal(r.stale.length,1,'cold-start cross-book outlier triggers stale-line fallback');
assert.equal(r.shop[0].bestBook,'BetMGM');
app.recordBookSnapshot({[key]:{draftkings:400,betmgm:410}},{[key]:{pct:19.2}});
const stored=JSON.parse(mem.dl_bookhist_v1);
assert.equal(stored[key].snaps.length,1,'snapshot persisted');
assert.equal(stored[key].snaps[0].c,19.2,'fair consensus persisted');
console.log('PASS market-move harness: steam, stale, line-shop, anti-false-positive, persistence');
